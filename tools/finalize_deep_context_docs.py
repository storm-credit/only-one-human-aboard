from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- DEEP-CONTEXT-410-STATUS:START -->"
END = "<!-- DEEP-CONTEXT-410-STATUS:END -->"


def write(rel: str, text: str) -> None:
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text.rstrip() + "\n", encoding="utf-8")


def upsert(rel: str, block: str) -> None:
    p = ROOT / rel
    text = p.read_text(encoding="utf-8")
    wrapped = f"{START}\n{block.strip()}\n{END}"
    if START in text and END in text:
        a = text.index(START)
        b = text.index(END, a) + len(END)
        text = text[:a] + wrapped + text[b:]
    else:
        lines = text.splitlines()
        insert = 0
        if lines and lines[0].strip() == "---":
            try:
                second = lines[1:].index("---") + 1
                insert = second + 1
            except ValueError:
                insert = 0
        else:
            for i, line in enumerate(lines):
                if line.startswith("# "):
                    insert = i + 1
                    break
        lines[insert:insert] = ["", wrapped, ""]
        text = "\n".join(lines)
    p.write_text(text.rstrip() + "\n", encoding="utf-8")


